/** Site-wide social card generated by src/app/opengraph-image.tsx. */
const DEFAULT_OG_IMAGE = { url: "/opengraph-image", width: 1200, height: 630, alt: SITE.name };

type PageSeo = {
  title: string;
  description: string;
  path: string;
  keywords?: string[];
  /** Absolute title skips the "| Polaris Tax Services" template, for pages that already include the brand. */
  absoluteTitle?: boolean;
  noIndex?: boolean;
  ogType?: "website" | "article";
  images?: { url: string; width?: number; height?: number; alt?: string }[];
};

/** Builds consistent metadata: canonical URL, Open Graph, Twitter and robots for a page. */
export function buildMetadata({
  title,
  description,
  path,
  keywords = [],
  absoluteTitle,
  noIndex,
  ogType = "website",
  images,
}: PageSeo): Metadata {
  const fullTitle = absoluteTitle ? title : `${title} | ${SITE.name}`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    keywords: [...keywords, ...CORE_KEYWORDS],
    alternates: { canonical: path },
    openGraph: {
      type: ogType,
      locale: SITE.locale,
      url: path,
      siteName: SITE.name,
      title: fullTitle,
      description,
      images: images ?? [DEFAULT_OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      site: SITE.twitter,
      images: (images ?? [DEFAULT_OG_IMAGE]).map((i) => i.url),
    },
    robots: noIndex ? { index: false, follow: true } : undefined,
  };
}

/* ---------- Structured data (schema.org JSON-LD) ---------- */

const ORG_ID = `${SITE.url}/#organization`;

