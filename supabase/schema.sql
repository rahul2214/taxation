-- Enable UUID extension if not already enabled
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. CUSTOMERS TABLE (Supabase Auth user.id UUID as primary key + int8 userid identity)
CREATE TABLE IF NOT EXISTS public.customers (
    id UUID NOT NULL,
    first_name TEXT NULL,
    last_name TEXT NULL,
    email TEXT NOT NULL,
    phone TEXT NULL,
    address TEXT NULL,
    role TEXT NOT NULL DEFAULT 'customer'::TEXT,
    signup_date TIMESTAMP WITH TIME ZONE NULL DEFAULT NOW(),
    created_at TIMESTAMP WITH TIME ZONE NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NULL DEFAULT NOW(),
    referral_code TEXT NULL,
    wallet_balance NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    referred_by TEXT NULL,                              -- Stores referrer's int8 userid value
    userid BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT customers_pkey PRIMARY KEY (id),
    CONSTRAINT customers_email_key UNIQUE (email),
    CONSTRAINT customers_referral_code_key UNIQUE (referral_code),
    CONSTRAINT customers_userid_key UNIQUE (userid)
) TABLESPACE pg_default;

-- Indexes for quick lookups
CREATE INDEX IF NOT EXISTS idx_customers_email ON public.customers USING btree (email) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_customers_role ON public.customers USING btree (role) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_customers_referral_code ON public.customers USING btree (referral_code) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_customers_userid ON public.customers USING btree (userid) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_customers_referred_by ON public.customers USING btree (referred_by) TABLESPACE pg_default;

-- 2. TAX DOCUMENTS TABLE
CREATE TABLE IF NOT EXISTS public.tax_documents (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    customer_id UUID NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
    customer_userid BIGINT REFERENCES public.customers(userid) ON DELETE CASCADE,
    document_name TEXT NOT NULL,
    file_url TEXT NOT NULL,
    document_type TEXT NOT NULL,               -- e.g., 'W-2', '1099', 'Tax Estimation'
    tax_year INTEGER,
    category TEXT NOT NULL DEFAULT 'Customer Upload', -- 'Customer Upload', 'Tax Estimation', 'Tax Return Draft', 'Final Document'
    uploader TEXT NOT NULL DEFAULT 'customer', -- 'customer' or 'admin'
    status TEXT NOT NULL DEFAULT 'Pending',    -- 'Pending', 'Approved', 'Rejected'
    upload_date TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tax_documents_customer_id ON public.tax_documents(customer_id);
CREATE INDEX IF NOT EXISTS idx_tax_documents_customer_userid ON public.tax_documents(customer_userid);
CREATE INDEX IF NOT EXISTS idx_tax_documents_status ON public.tax_documents(status);
CREATE INDEX IF NOT EXISTS idx_tax_documents_category ON public.tax_documents(category);

-- 3. APPOINTMENTS TABLE
CREATE TABLE IF NOT EXISTS public.appointments (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE SET NULL,
    customer_userid BIGINT REFERENCES public.customers(userid) ON DELETE SET NULL,
    name TEXT,
    email TEXT NOT NULL,
    phone TEXT,
    service TEXT,
    appointment_date TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending',    -- 'Pending', 'Confirmed', 'Completed', 'Cancelled'
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_appointments_customer_id ON public.appointments(customer_id);
CREATE INDEX IF NOT EXISTS idx_appointments_customer_userid ON public.appointments(customer_userid);
CREATE INDEX IF NOT EXISTS idx_appointments_status ON public.appointments(status);
CREATE INDEX IF NOT EXISTS idx_appointments_date ON public.appointments(appointment_date);

-- 4. WALLET TRANSACTIONS TABLE (Tracks referral bonuses, welcome credits, discounts)
CREATE TABLE IF NOT EXISTS public.wallet_transactions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    customer_id UUID NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
    customer_userid BIGINT REFERENCES public.customers(userid) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL,
    type TEXT NOT NULL,                         -- 'referral_bonus', 'welcome_bonus', 'service_discount', 'manual_adjustment'
    description TEXT,
    reference_id TEXT,                          -- e.g. referral id or invoice id
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_wallet_tx_customer ON public.wallet_transactions(customer_id);
CREATE INDEX IF NOT EXISTS idx_wallet_tx_customer_userid ON public.wallet_transactions(customer_userid);
CREATE INDEX IF NOT EXISTS idx_wallet_tx_created ON public.wallet_transactions(created_at);

-- 6. SITE SETTINGS TABLE
CREATE TABLE IF NOT EXISTS public.site_settings (
    id TEXT PRIMARY KEY DEFAULT 'global',
    current_year_form_url TEXT,
    prior_year_form_url TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Insert default site_settings row if it doesn't exist
INSERT INTO public.site_settings (id, current_year_form_url, prior_year_form_url)
VALUES ('global', null, null)
ON CONFLICT (id) DO NOTHING;

-- 6. ADMINS TABLE (For storing admin credentials & details)
CREATE TABLE IF NOT EXISTS public.admins (
    id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    email TEXT UNIQUE NOT NULL,
    password TEXT,                                 -- Stored admin credentials / password
    name TEXT,
    role TEXT NOT NULL DEFAULT 'admin',            -- 'admin' or 'superadmin'
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_admins_email ON public.admins(email);

