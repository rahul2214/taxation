-- 7. Enable RLS on roles
ALTER TABLE public.roles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow anon read roles" ON public.roles;
CREATE POLICY "Allow anon read roles"
    ON public.roles FOR SELECT
    USING (true);
