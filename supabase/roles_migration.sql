RETURNS TRIGGER AS $$
BEGIN
    IF NEW.role_id IS NOT NULL AND (TG_OP = 'INSERT' OR NEW.role_id IS DISTINCT FROM OLD.role_id) THEN
        SELECT name INTO NEW.role FROM public.roles WHERE id = NEW.role_id;
        IF NEW.role IS NULL THEN
            NEW.role := 'admin';
        END IF;
