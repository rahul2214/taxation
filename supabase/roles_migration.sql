-- 1. Create the Roles table
CREATE TABLE IF NOT EXISTS public.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name TEXT NOT NULL UNIQUE,
    description TEXT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT roles_pkey PRIMARY KEY (id),
    CONSTRAINT roles_name_key UNIQUE (name)
) TABLESPACE pg_default;

-- 2. Seed standard roles (admin: 1, customer: 2, superadmin: 3)
INSERT INTO public.roles (id, name, description)
VALUES 
    (1, 'admin', 'Administrator with management access'),
    (2, 'customer', 'Standard client / customer account'),
    (3, 'superadmin', 'Super administrator with full privileges')
ON CONFLICT (id) DO UPDATE SET 
    name = EXCLUDED.name, 
    description = EXCLUDED.description;

-- Ensure sequence matches max id
SELECT setval(pg_get_serial_sequence('public.roles', 'id'), COALESCE((SELECT MAX(id) FROM public.roles), 1));

-- 3. Add role_id to customers and establish foreign key
ALTER TABLE public.customers 
ADD COLUMN IF NOT EXISTS role_id BIGINT;

-- Backfill existing customers
UPDATE public.customers
SET role_id = CASE 
    WHEN role = 'admin' THEN 1
    WHEN role = 'superadmin' THEN 3
    ELSE 2
END
WHERE role_id IS NULL;

-- Set default role_id to 2 (customer)
ALTER TABLE public.customers
ALTER COLUMN role_id SET DEFAULT 2;

-- Add foreign key constraint if not exists
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'customers_role_id_fkey'
    ) THEN
        ALTER TABLE public.customers
        ADD CONSTRAINT customers_role_id_fkey
        FOREIGN KEY (role_id) REFERENCES public.roles(id) ON UPDATE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_customers_role_id ON public.customers USING btree (role_id);

-- 4. Add role_id to admins and establish foreign key
ALTER TABLE public.admins 
ADD COLUMN IF NOT EXISTS role_id BIGINT;

-- Backfill existing admins
UPDATE public.admins
SET role_id = CASE 
    WHEN role = 'superadmin' THEN 3
    ELSE 1
END
WHERE role_id IS NULL;

-- Set default role_id to 1 (admin)
ALTER TABLE public.admins
ALTER COLUMN role_id SET DEFAULT 1;

-- Add foreign key constraint if not exists
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'admins_role_id_fkey'
    ) THEN
        ALTER TABLE public.admins
        ADD CONSTRAINT admins_role_id_fkey
        FOREIGN KEY (role_id) REFERENCES public.roles(id) ON UPDATE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_admins_role_id ON public.admins USING btree (role_id);

-- 5. Automatic synchronization trigger for customers (keeps role_id & role text in sync)
CREATE OR REPLACE FUNCTION public.sync_customer_role()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.role_id IS NOT NULL AND (TG_OP = 'INSERT' OR NEW.role_id IS DISTINCT FROM OLD.role_id) THEN
        SELECT name INTO NEW.role FROM public.roles WHERE id = NEW.role_id;
        IF NEW.role IS NULL THEN
            NEW.role := 'customer';
        END IF;
    ELSIF NEW.role IS NOT NULL AND (NEW.role_id IS NULL OR NEW.role IS DISTINCT FROM OLD.role) THEN
        SELECT id INTO NEW.role_id FROM public.roles WHERE name = NEW.role;
        IF NEW.role_id IS NULL THEN
            NEW.role_id := 2;
        END IF;
    END IF;

    IF NEW.role_id IS NULL THEN
        NEW.role_id := 2;
    END IF;
    IF NEW.role IS NULL THEN
        NEW.role := 'customer';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sync_customer_role ON public.customers;
CREATE TRIGGER trg_sync_customer_role
BEFORE INSERT OR UPDATE ON public.customers
FOR EACH ROW EXECUTE FUNCTION public.sync_customer_role();

-- 6. Automatic synchronization trigger for admins (keeps role_id & role text in sync)
