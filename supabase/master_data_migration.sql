-- 3. Foreign keys on appointments and contacts.
--    The text columns (appointments.service, contacts.subject) stay as a snapshot
--    of the label, so old records still read correctly if a value is renamed or deleted.
ALTER TABLE public.appointments
    ADD COLUMN IF NOT EXISTS service_id BIGINT REFERENCES public.master_data(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS time_slot_id BIGINT REFERENCES public.master_data(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS time_slot TEXT;

ALTER TABLE public.contacts
    ADD COLUMN IF NOT EXISTS topic_id BIGINT REFERENCES public.master_data(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_appointments_service_id ON public.appointments(service_id);
CREATE INDEX IF NOT EXISTS idx_appointments_time_slot_id ON public.appointments(time_slot_id);
CREATE INDEX IF NOT EXISTS idx_contacts_topic_id ON public.contacts(topic_id);

-- 4. Backfill ids on existing rows where the stored text matches a master label
UPDATE public.appointments a
SET service_id = m.id
FROM public.master_data m
WHERE m.category = 'appointment_service' AND a.service = m.label AND a.service_id IS NULL;

UPDATE public.contacts c
SET topic_id = m.id
FROM public.master_data m
WHERE m.category = 'contact_topic' AND c.subject = m.label AND c.topic_id IS NULL;

-- Make PostgREST pick up the changes immediately
NOTIFY pgrst, 'reload schema';
