-- Polaris Tax Services - Master data for form dropdowns
--   * appointment_service : "What do you need help with?" (booking forms)
--   * appointment_time    : "Best time" / preferred time window (booking forms)
--   * contact_topic       : "Topic" (contact page)
-- Stores the selected master_data id on appointments and contacts.
-- Run AFTER contacts_migration.sql.
-- Run in Supabase: Dashboard -> SQL Editor -> New Query -> Run
-- ==============================================================================

-- 1. Master data table
CREATE TABLE IF NOT EXISTS public.master_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    label TEXT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT master_data_category_label_key UNIQUE (category, label)
);

CREATE INDEX IF NOT EXISTS idx_master_data_category ON public.master_data(category, sort_order);

ALTER TABLE public.master_data ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow anon read/write master_data" ON public.master_data;
CREATE POLICY "Allow anon read/write master_data"
    ON public.master_data FOR ALL
    USING (true)
    WITH CHECK (true);

